// Latest way to select the element is by using querySelector method and querySelectorAll

// Use the querySelector method to select only the first element of given selector

let c = document.querySelector("h1"); // Only select the first element of h1 tag
console.dir(c); 


// Use the querySelectorAll method to select all elements of given selector
let d = document.querySelectorAll("h1");
console.dir(d);