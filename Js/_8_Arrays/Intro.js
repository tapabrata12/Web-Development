// Arrays are to store multiple values in a single variable.
// They can hold any type of data, including numbers, strings, and even other arrays.

// Declaration

let arr = [];

arr = [1, 2, 3.6, 'Tapabrata', true]; // Array Initialization

console.log(arr); // Output: [1, 2, 3.6, 'Tapabrata', true]

// Index:

arr[0] = 10; // Changing the first element
console.log(arr);
console.log(arr[0]); // Output: 10
console.log(arr[1]); // Output: 2
console.log(arr[3]); // Output: 'Tapabrata'

